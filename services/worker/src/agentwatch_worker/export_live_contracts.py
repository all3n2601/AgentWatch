"""Export the live router OpenAPI and matching TypeScript data contracts."""

import json
from pathlib import Path

from fastapi.openapi.utils import get_openapi

from agentwatch_worker.live_api import router


def openapi_document() -> dict:
    return get_openapi(
        title="AgentWatch live ingestion API",
        version="live-contracts-v1",
        routes=router.routes,
        description="Bounded incremental ingestion and UUID-specific polling. "
        "See docs/live-ingestion.md for lifecycle, retry, gap and cleanup semantics.",
    )


def typescript_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript_type(item) for item in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(typescript_type(item) for item in schema["oneOf"])
    kind = schema.get("type")
    if kind is None:
        return "unknown"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "string":
        return "string"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{typescript_type(schema['items'])}>"
    if kind == "object" and "properties" not in schema:
        value = schema.get("additionalProperties", {})
        return f"Record<string, {typescript_type(value) if isinstance(value, dict) else 'unknown'}>"
    raise ValueError(f"Unsupported TypeScript schema: {schema}")


def typescript_document(document: dict) -> str:
    lines = [
        "// Generated by uv run python -m agentwatch_worker.export_live_contracts.",
        "// Wire types only: the service validates semantic invariants. See docs/live-ingestion.md.",
        "",
    ]
    for name, schema in sorted(document["components"]["schemas"].items()):
        lines.append(f"export interface {name} {{")
        required = set(schema.get("required", []))
        for key, field in schema["properties"].items():
            optional = "" if key in required else "?"
            lines.append(f"  {key}{optional}: {typescript_type(field)};")
        lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> None:
    root = Path(__file__).resolve().parents[4]
    document = openapi_document()
    (root / "api/openapi/live.json").write_text(json.dumps(document, indent=2) + "\n")
    (root / "packages/sdk-typescript/src/live.ts").write_text(typescript_document(document))


if __name__ == "__main__":
    main()
