"use client";

import { Sparkles } from "lucide-react";
import { useState } from "react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import type { Fact, Insight } from "@/lib/insights";

type Request = { kind: "overview" } | { kind: "run"; runId: string };
type State =
  | { status: "idle" }
  | { status: "loading" }
  | { status: "error"; message: string }
  | {
      status: "ready";
      facts: Fact[];
      insight: Insight;
      model: string;
      generatedAt: string;
      cached: boolean;
    };

/**
 * A written summary of the figures on this page. It is generated text, labelled as such: each
 * point names the facts it rests on, and the full list the model saw is one click away.
 */
export function InsightPanel({ request }: { request: Request }) {
  const [state, setState] = useState<State>({ status: "idle" });
  const [showFacts, setShowFacts] = useState(false);

  async function generate() {
    setState({ status: "loading" });
    try {
      const response = await fetch("/api/insights", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(request),
      });
      const body = await response.json();
      if (!response.ok) throw new Error(body.error ?? "Summary unavailable.");
      setState({ status: "ready", ...body });
    } catch (error) {
      setState({
        status: "error",
        message:
          error instanceof Error ? error.message : "Summary unavailable.",
      });
    }
  }

  const loading = state.status === "loading";
  return (
    <Card className="gap-0 p-5">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="min-w-0">
          <h2 className="flex items-center gap-2 text-sm font-semibold tracking-tight">
            <Sparkles className="size-4 text-primary" aria-hidden />
            AI summary
          </h2>
          <p className="mt-1 text-xs text-muted-foreground">
            Written by a language model from the figures on this page. It
            explains the numbers; it does not measure anything.
          </p>
        </div>
        <Button
          size="sm"
          variant="outline"
          disabled={loading}
          onClick={() => void generate()}
        >
          {loading
            ? "Summarizing…"
            : state.status === "ready"
              ? "Regenerate"
              : "Summarize"}
        </Button>
      </div>
      {state.status === "error" && (
        <p role="alert" className="mt-4 text-xs text-amber-200">
          {state.message}
        </p>
      )}
      {state.status === "ready" && (
        <div className="mt-4 space-y-4">
          {state.insight.summary && (
            <p className="text-sm leading-6">{state.insight.summary}</p>
          )}
          {state.insight.points.length > 0 ? (
            <ul className="space-y-2 text-sm leading-6">
              {state.insight.points.map((point) => (
                <li key={point.text} className="flex gap-2">
                  <span aria-hidden className="text-muted-foreground">
                    •
                  </span>
                  <span>
                    {point.text}{" "}
                    {point.facts.map((id) => (
                      <Badge
                        key={id}
                        variant="outline"
                        className="mr-1 px-1.5 font-mono text-[10px]"
                        title={state.facts.find((fact) => fact.id === id)?.text}
                      >
                        {id}
                      </Badge>
                    ))}
                  </span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-xs text-muted-foreground">
              No point in the model&apos;s reply matched the figures, so nothing
              is shown.
            </p>
          )}
          {state.insight.caveats.length > 0 && (
            <ul className="space-y-1 text-xs text-muted-foreground">
              {state.insight.caveats.map((caveat) => (
                <li key={caveat}>{caveat}</li>
              ))}
            </ul>
          )}
          <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-[11px] text-muted-foreground">
            <span>
              Generated by {state.model}
              {state.cached ? " (reused from a recent request)" : ""} ·{" "}
              <time dateTime={state.generatedAt} suppressHydrationWarning>
                {new Date(state.generatedAt).toLocaleTimeString()}
              </time>
            </span>
            {state.insight.dropped > 0 && (
              <span>
                {state.insight.dropped} statement
                {state.insight.dropped === 1 ? "" : "s"} left out: cited no
                known fact or repeated a figure the facts do not contain.
              </span>
            )}
            <button
              type="button"
              className="underline underline-offset-2 hover:text-foreground"
              aria-expanded={showFacts}
              onClick={() => setShowFacts(!showFacts)}
            >
              {showFacts ? "Hide" : "Show"} the figures it was given
            </button>
          </div>
          {showFacts && (
            <ol className="space-y-1 rounded-md border bg-background/40 p-3 text-xs">
              {state.facts.map((fact) => (
                <li key={fact.id} className="flex gap-2">
                  <span className="font-mono text-muted-foreground">
                    {fact.id}
                  </span>
                  <span>{fact.text}</span>
                </li>
              ))}
            </ol>
          )}
        </div>
      )}
    </Card>
  );
}
